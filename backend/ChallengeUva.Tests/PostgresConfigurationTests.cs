using System;
using System.Linq;
using ChallengeUva.Infrastructure.Data;
using ChallengeUva.Infrastructure.Data.Contexts;
using FluentAssertions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Npgsql;
using Xunit;

namespace ChallengeUva.Tests;

public class PostgresConfigurationTests
{
    [Fact] public void ParsesDatabaseUrlWithoutLosingEncodedCredentials()
    {
        var password = Guid.NewGuid() + ":@/;?#%";
        var user = "test-user";
        var url = $"postgresql://{user}:{Uri.EscapeDataString(password)}@localhost:5433/shop_test";
        var parsed = new NpgsqlConnectionStringBuilder(PostgresConnection.Parse(url));
        parsed.Host.Should().Be("localhost"); parsed.Port.Should().Be(5433);
        parsed.Username.Should().Be(user); parsed.Password.Should().Be(password);
        parsed.Database.Should().Be("shop_test"); parsed.SslMode.Should().Be(SslMode.Require);
        parsed.MaxPoolSize.Should().Be(10);
    }

    [Fact] public void SupportsPostgresSchemeAndExplicitSslMode()
    {
        var parsed = new NpgsqlConnectionStringBuilder(PostgresConnection.Parse(
            $"postgres://test-user:{Guid.NewGuid():N}@localhost/shop_test?sslmode=disable"));
        parsed.Port.Should().Be(5432); parsed.SslMode.Should().Be(SslMode.Disable);
    }

    [Fact] public void KeepsNativeNpgsqlConnectionString()
    {
        var original = new NpgsqlConnectionStringBuilder {
            Host = "localhost", Database = "shop_test", Username = "test-user", Password = Guid.NewGuid().ToString(), SslMode = SslMode.VerifyFull,
        };
        var parsed = new NpgsqlConnectionStringBuilder(PostgresConnection.Parse(original.ConnectionString));
        parsed.Password.Should().Be(original.Password); parsed.SslMode.Should().Be(SslMode.VerifyFull);
    }

    [Fact] public void InvalidConnectionErrorDoesNotExposeCredentials()
    {
        var secret = Guid.NewGuid().ToString();
        Action action = () => PostgresConnection.Parse($"postgresql://{secret}@");
        var exception = action.Should().Throw<InvalidOperationException>().Which;
        exception.Message.Should().NotContain(secret); exception.InnerException.Should().BeNull();
    }

    [Fact] public void PostgresMigrationUsesNativeTypesAndDoesNotReuseSqliteMigrations()
    {
        using var db = new PostgresChallengeUvaContext(new DbContextOptionsBuilder<PostgresChallengeUvaContext>().UseNpgsql().Options);
        db.Database.GetMigrations().Should().ContainSingle().Which.Should().EndWith("InitialPostgres");
        var sql = db.GetService<IMigrator>().GenerateScript();
        sql.Should().Contain("GENERATED BY DEFAULT AS IDENTITY").And.Contain("uuid").And.Contain("boolean")
            .And.Contain("timestamp with time zone").And.Contain("bigint").And.Contain("ContactMessages")
            .And.NotContain("AUTOINCREMENT").And.NotContain("InitialSqlite");
    }

    [Fact] public void SqliteKeepsItsOriginalMigrationHistory()
    {
        using var db = new ChallengeUvaContext(new DbContextOptionsBuilder<ChallengeUvaContext>().UseSqlite("Data Source=:memory:").Options);
        db.Database.GetMigrations().Should().HaveCount(3).And.NotContain(id => id.EndsWith("InitialPostgres"));
    }
}
